def format_timestamp_srt(seconds: float) -> str:
    """Format seconds into SRT timestamp HH:MM:SS,mmm."""
    hrs = int(seconds // 3600)
    mins = int((seconds % 3600) // 60)
    secs = int(seconds % 60)
    milli = int((seconds - int(seconds)) * 1000)
    return f"{hrs:02d}:{mins:02d}:{secs:02d},{milli:03d}"

def format_timestamp_vtt(seconds: float) -> str:
    """Format seconds into WebVTT timestamp HH:MM:SS.mmm."""
    hrs = int(seconds // 3600)
    mins = int((seconds % 3600) // 60)
    secs = int(seconds % 60)
    milli = int((seconds - int(seconds)) * 1000)
    return f"{hrs:02d}:{mins:02d}:{secs:02d}.{milli:03d}"

def generate_srt(turn_timestamps: List[Dict[str, Any]]) -> str:
    """Generate SRT subtitle file content from turn timestamps."""
    lines = []
    for idx, turn in enumerate(turn_timestamps, start=1):
        start_ts = format_timestamp_srt(turn["start"])
        end_ts = format_timestamp_srt(turn["end"])
        speaker = turn.get("speaker", "SPEAKER")
        text = turn.get("text", "")
        lines.append(f"{idx}\n{start_ts} --> {end_ts}\n[{speaker}]: {text}\n")
    return "\n".join(lines)

def generate_vtt(turn_timestamps: List[Dict[str, Any]]) -> str:
    """Generate WebVTT subtitle file content from turn timestamps."""
    lines = ["WEBVTT\n"]
    for turn in turn_timestamps:
        start_ts = format_timestamp_vtt(turn["start"])
        end_ts = format_timestamp_vtt(turn["end"])
        speaker = turn.get("speaker", "SPEAKER")
        text = turn.get("text", "")
        lines.append(f"{start_ts} --> {end_ts}\n<v {speaker}>{text}\n")
    return "\n".join(lines)

def generate_show_notes_markdown(
    title: str,
    topic: str,
    duration_s: float,
    research_brief: Dict[str, Any],
    outline: Dict[str, Any],
    turn_timestamps: List[Dict[str, Any]],
) -> str:
    """Generate comprehensive podcast show notes in GitHub-flavored Markdown."""
    mins = int(duration_s // 60)
    secs = int(duration_s % 60)
    duration_str = f"{mins}m {secs}s"

    key_points_md = "\n".join([f"- {kp}" for kp in research_brief.get("key_points", [])])
    key_facts_md = "\n".join([f"- {kf}" for kf in research_brief.get("key_facts", [])])
    sources_md = "\n".join([f"- {src}" for src in research_brief.get("sources", [])])

    # Build chapter timestamps
    chapters_md = []
    segments = outline.get("segments", [])
    if turn_timestamps:
        # Approximate segment breakdown
        chapters_md.append(f"- **00:00** - Cold Open & Hook")
        for seg in segments:
            # Match first turn in segment or time approximation
            chapters_md.append(f"- **Segment** - {seg.get('title', 'Discussion')}")
        chapters_md.append(f"- **Recap & Outro** - Final takeaways & wrap-up")

    return f"""# {title}

**Topic**: {topic}  
**Runtime**: {duration_str}  
**Generated By**: PodcastAI powered by Sarvam AI

---

## Episode Synopsis
{outline.get('intro', '')}

---

## Key Discussion Points
{key_points_md or '- In-depth analysis of the topic.'}

## Key Facts & Grounded Insights
{key_facts_md or '- Grounded facts from source materials.'}

---

## Chapters & Timestamps
{chr(10).join(chapters_md)}

---

## References & Sources
{sources_md or '- Generated from foundational knowledge.'}

*PodcastAI — Automated multi-speaker podcast generation using Sarvam AI Bulbul and LLMs.*
"""

def convert_wav_to_mp3(wav_path: str, mp3_path: str, metadata: Optional[Dict[str, str]] = None) -> bool:
    """Convert WAV to MP3 with optional ID3 metadata tags using pydub/mutagen."""
    try:
        from pydub import AudioSegment
        seg = AudioSegment.from_wav(wav_path)
        tags = {}
        if metadata:
            tags = {
                "title": metadata.get("title", "Podcast Episode"),
                "artist": metadata.get("artist", "PodcastAI"),
                "album": metadata.get("album", "PodcastAI Shows"),
                "comments": metadata.get("description", ""),
            }
        seg.export(mp3_path, format="mp3", bitrate="192k", tags=tags)
        return True
    except Exception as e:
        logger.warning(f"Could not convert to MP3 ({e}). WAV master remains available.")
        return False

